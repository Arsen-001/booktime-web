import { chromium } from '@playwright/test';
import { acquireBrowserSlot } from '../../../../scripts/pw-slots.mjs';
const release = await acquireBrowserSlot();
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errs = [];
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
await page.goto('http://localhost:3710/b/mariam-nails?demo=guest&sphere=nails&lang=ru&theme=light', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
await page.screenshot({ path: 'qa/shots/online/g1-3-m1/phone-public.png', fullPage: true });
await page.goto('http://localhost:3710/biz/online/requests?demo=individual&sphere=nails&lang=ru&theme=light', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
await page.screenshot({ path: 'qa/shots/online/g1-3-m1/phone-requests.png', fullPage: true });
await page.goto('http://localhost:3710/biz/online/places?demo=individual&sphere=nails&lang=ru&theme=light', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
await page.screenshot({ path: 'qa/shots/online/g1-3-m1/phone-places.png', fullPage: true });
await page.goto('http://localhost:3710/biz/online/links?demo=owner&sphere=nails&lang=ru&theme=light', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
console.log('errs', errs);
await browser.close();
release();
