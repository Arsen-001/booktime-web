import { chromium } from '@playwright/test';
import { acquireBrowserSlot } from '../../../../scripts/pw-slots.mjs';
const release = await acquireBrowserSlot();
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
const errs = [];
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
await page.goto('http://localhost:3710/biz/online/requests?demo=individual&sphere=nails&lang=ru&theme=light', { waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
console.log('BEFORE', await page.locator('body').innerText());
await page.screenshot({ path: 'qa/shots/online/g1-3-m1/f067-requests-before.png', fullPage: true });
const confirmBtn = page.getByRole('button', { name: 'Подтвердить' }).first();
await confirmBtn.click();
await page.waitForTimeout(1000);
console.log('AFTER-CONFIRM', await page.locator('body').innerText());
await page.screenshot({ path: 'qa/shots/online/g1-3-m1/f067-requests-after.png', fullPage: true });
console.log('errs', errs);
await browser.close();
release();
