import { acquireBrowserSlot } from '../../../../scripts/pw-slots.mjs';
import { chromium } from '@playwright/test';
const release = await acquireBrowserSlot();
const b = await chromium.launch();
const p = await b.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.type()+': ' + m.text()); });
await p.setViewportSize({ width: 1440, height: 900 });
await p.goto('http://localhost:3710/biz/loyalty?demo=owner&sphere=nails&lang=ru&theme=light');
await p.waitForTimeout(2500);
await p.screenshot({ path: 'qa/shots/loyalty-g1-2/hub/1-desktop.png', fullPage: true });
await p.setViewportSize({ width: 390, height: 844 });
await p.waitForTimeout(500);
await p.screenshot({ path: 'qa/shots/loyalty-g1-2/hub/2-mobile.png', fullPage: true });
console.log('ERRORS:', JSON.stringify(errs));
await b.close();
release();
