import { acquireBrowserSlot } from '../../../../scripts/pw-slots.mjs';
import { chromium } from '@playwright/test';
const release = await acquireBrowserSlot();
const b = await chromium.launch();
const p = await b.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
p.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
await p.setViewportSize({ width: 1440, height: 900 });
await p.goto('http://localhost:3710/biz/journal?demo=owner&sphere=nails&lang=ru&theme=light');
await p.waitForTimeout(1800);
await p.getByText('Педикюр классический').first().click();
await p.waitForTimeout(700);
await p.getByRole('tab', { name: 'Лояльность' }).click();
await p.waitForTimeout(900);
await p.screenshot({ path: 'qa/shots/loyalty-g1-2/explore1/1-loyalty-tab.png', fullPage: true });
console.log('BODY_TEXT_START');
console.log(await p.locator('[role=tabpanel]').first().innerText().catch(() => 'n/a'));
console.log('BODY_TEXT_END');
console.log('ERRORS:', JSON.stringify(errs));
await b.close();
release();
