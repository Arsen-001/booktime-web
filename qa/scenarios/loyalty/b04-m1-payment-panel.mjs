import { acquireBrowserSlot } from '../../../scripts/pw-slots.mjs';
import { chromium } from '@playwright/test';
const release = await acquireBrowserSlot();
const b = await chromium.launch();
const p = await b.newPage();
await p.setViewportSize({width:1440,height:900});
await p.goto('http://localhost:3710/biz/journal?demo=owner&sphere=nails&lang=ru&theme=light');
await p.waitForTimeout(1800);
await p.getByText('Педикюр классический').first().click();
await p.waitForTimeout(700);
await p.getByRole('tab', { name: 'Лояльность' }).click();
await p.waitForTimeout(900);
await p.screenshot({ path: 'qa/shots/loyalty-b04-m1/scenario1/1-tab-open.png', fullPage: true });
await p.getByText('Акция «Скидка постоянному гостю»').click();
await p.waitForTimeout(400);
await p.getByText('Списать бонусы').click();
await p.waitForTimeout(500);
await p.screenshot({ path: 'qa/shots/loyalty-b04-m1/scenario1/2-lines-applied.png', fullPage: true });
const saveBtn = p.getByRole('button', { name: 'Сохранить изменения' });
console.log('save disabled with only loyalty lines applied:', await saveBtn.isDisabled());
await b.close();
release();
