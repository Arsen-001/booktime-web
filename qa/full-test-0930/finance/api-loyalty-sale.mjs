import { createJiti } from 'jiti';
const root = '/Users/arsen/WebstormProjects/booking-platform';
const jiti = createJiti(import.meta.url, { alias: { '@docs': root + '/docs', '@messages': root + '/messages', '@': root + '/src' }, jsx: true });
const db = await jiti.import(root + '/src/mock/db.ts');
await db.bootDb();
const fin = await jiti.import(root + '/src/api/finance.ts');
const S = () => db.useDb.getState();
const biz = 'biz_atam';
const loc = S().core.businesses.find((b) => b.id === biz).locationIds[0];
const accs = await fin.listAccountsWithBalance(biz);
const cash = accs.find((a) => a.kind === 'cash');
let pass = 0, fail = 0; const check = (n, ok, i = '') => { ok ? pass++ : fail++; console.log(ok ? 'PASS' : 'FAIL', n, i); };
const op = await fin.recordLoyaltySale(biz, { kind: 'membership', locationId: loc, amount: 25000, methodKey: 'cash', label: 'Абонемент QA' });
const after = (await fin.listAccountsWithBalance(biz)).find((a) => a.id === cash.id).balance;
const item = (await fin.listItems(biz)).find((i) => i.id === op.itemId);
check('продажа абонемента 25 000 наличными → +25 000 в кассе', after === cash.balance + 25000, `${cash.balance} → ${after}`);
check('статья «Продажа абонементов»', /абонем/i.test(item?.name ?? ''), item?.name);
const top = await fin.recordLoyaltySale(biz, { kind: 'accountTopUp', locationId: loc, amount: 5000, methodKey: 'card' });
check('пополнение счёта картой → операция source account (отменяют в Лояльности)', top.source === 'account' && top.method === 'card');
console.log(`ИТОГ ${pass}/${pass + fail}`); process.exit(0);
