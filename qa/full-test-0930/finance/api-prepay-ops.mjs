// Решение владельца 01.10.2026: предоплата — своя операция; визит добирает остаток; «Вернул» — обратная операция
import { createJiti } from 'jiti';
const root = process.env.ROOT || '/Users/arsen/WebstormProjects/booking-platform';
const jiti = createJiti(import.meta.url, { alias: { '@docs': root + '/docs', '@messages': root + '/messages', '@': root + '/src' }, jsx: true });
const db = await jiti.import(root + '/src/mock/db.ts');
await db.bootDb();
const fin = await jiti.import(root + '/src/api/finance.ts');
const online = await jiti.import(root + '/src/api/online.ts');
const journal = await jiti.import(root + '/src/api/journal.ts');
const S = () => db.useDb.getState();
let pass = 0, fail = 0;
const check = (n, ok, info = '') => { ok ? pass++ : fail++; console.log(ok ? 'PASS' : 'FAIL', n, info); };
const b0 = S().core.bookings.find((b) => b.status === 'awaiting_prepayment' && b.prepayment && !b.prepayment.paid && !(b.goods?.length));
// Сценарий координатора: визит 7 000, предоплата 2 100
S().setCore((c) => ({ ...c, bookings: c.bookings.map((b) => (b.id === b0.id ? { ...b, total: 7000, services: [{ ...b.services[0], price: 7000, qty: 1 }], prepayment: { ...b.prepayment, amount: 2100 } } : b)) }));
const biz = b0.businessId;
const opsOf = () => S().areas.finance.operations.filter((o) => o.refId === b0.id && !o.cancelled);
const net = () => opsOf().reduce((a, o) => a + (o.kind === 'income' ? o.amount : -o.amount), 0);
await online.confirmPrepaymentReceived(b0.id);
check('«Деньги пришли» → операция +2 100 (перевод на реквизиты)', opsOf().length === 1 && opsOf()[0].amount === 2100 && opsOf()[0].kind === 'income' && opsOf()[0].method === 'transfer', JSON.stringify(opsOf().map((o) => [o.kind, o.amount, o.method])));
const acc = S().areas.finance.accounts.find((a) => a.id === opsOf()[0]?.accountId);
check('касса операции — «Предоплата на реквизиты»', acc?.systemKey === 'prepayment', acc?.name);
await online.confirmPrepaymentReceived(b0.id).catch(() => {});
check('повторное «Деньги пришли» не дублирует', opsOf().length === 1);
let s = await fin.getBookingPaymentSummary(biz, b0.id);
check('окно оплаты просит 4 900', s.due === 4900, String(s.due));
const tiles = await fin.listBookingPaymentTiles(biz);
s = await fin.payBookingQuick(biz, b0.id, tiles.find((t) => t.kind === 'cash').key);
check('«Наличные» на визите → +4 900', opsOf().filter((o) => o.method === 'cash').reduce((a, o) => a + o.amount, 0) === 4900);
check('итого по визиту в финансах 7 000', net() === 7000, String(net()));
const day = await fin.getDayMoneySummary(biz, opsOf()[0].date.slice(0, 10));
console.log('  day', JSON.stringify(day));
await fin.refundBookingFull(biz, b0.id, 'отмена');
check('полный возврат визита возвращает кассовые 4 900 (не трогает предоплату)', net() === 2100, String(net()));
await journal.markPrepaymentRefunded(b0.id);
check('«Вернул» → обратная операция −2 100, итог 0', net() === 0 && opsOf().some((o) => o.kind === 'expense' && o.amount === 2100 && o.lineLabel === 'Предоплата'), String(net()));
await journal.markPrepaymentRefunded(b0.id);
check('повторное «Вернул» не дублирует', net() === 0, String(net()));
const pOp = opsOf().find((o) => o.lineLabel === 'Предоплата');
check('операцию предоплаты нельзя отменить со страницы операции', await fin.cancelOperation(biz, pOp.id).then(() => false, (e) => e.code === 'operation_linked'));
console.log(`ИТОГ ${pass}/${pass + fail}`);
process.exit(0);
