import type { Namespace } from '@/i18n/config';
import { isLocalizablePath } from '@/i18n/localePath';

/**
 * Какие словари браузер получает вместе со страницей (скорость публичных страниц, 05.10.2026).
 *
 * Все 21 словарь — около 1,3 МБ текста на язык; раньше они целиком ехали в HTML каждой страницы (330 КБ сжатыми),
 * и телефон на медленной сети ждал их до первой отрисовки. Публичным страницам (главная, поиск, страница салона,
 * «Для бизнеса», поддержка, юридические) нужны только словари ниже — их экраны не подключают кабинет.
 * Остальные страницы получают все словари, как раньше. Переход с публичной страницы в кабинет (или в профиль)
 * сначала догружает все словари (src/i18n/IntlProvider.tsx, адрес /i18n/<язык>), а уже потом показывает новую страницу.
 *
 * Добавили на публичную страницу компонент с useT('<другой словарь>') — допишите словарь сюда. Если забыть, текст
 * не пропадёт: провайдер поймает отсутствующий ключ, догрузит все словари и перерисует страницу, а в консоли
 * будет `[i18n:missing]` (его ловит scripts/measure.mjs).
 */
export const PUBLIC_NAMESPACES = ['common', 'ui', 'client', 'online', 'orders'] as const satisfies readonly Namespace[];

/**
 * Кроме страниц с языком в адресе: страница салона со всеми подстраницами (запись, о салоне, анкета, «мои записи»,
 * виджет), карточка места, запись из «Свободно сегодня» и вход — куда ведут ссылки с публичных страниц
 */
const PUBLIC_EXTRA = [/^\/b\/[^/]+(\/.*)?$/, /^\/places\/[^/]+$/, /^\/book$/, /^\/login$/];

/**
 * Словари для страницы (путь без языкового префикса и без ?query): публичная — PUBLIC_NAMESPACES,
 * любая другая — null (все словари).
 */
export function namespacesForPath(pathname: string | null | undefined): readonly Namespace[] | null {
  if (!pathname) return null;
  return isLocalizablePath(pathname) || PUBLIC_EXTRA.some((re) => re.test(pathname)) ? PUBLIC_NAMESPACES : null;
}

/** Заголовок запроса с путём страницы без языка (ставит src/proxy.ts; читает корневой layout) */
export const PATHNAME_HEADER = 'x-bt-path';
