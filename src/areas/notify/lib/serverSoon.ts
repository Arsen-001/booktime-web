import { isApiMode } from '@/api/http';

/**
 * Типы каталога, которые экран настраивает, а сервер ПОКА не отправляет (охват ТЗ 06.10.2026, п. 3.2 и п. 4 №4): в режиме
 * `api` у них метка «Скоро» в списке и пояснение на странице типа, чтобы салон не думал, что сообщение уходит. В демо
 * (`mock`) метки нет — там журнал отправок показывает всё каталогом.
 *
 * Сервер шлёт (06.10.2026, booktime-backend jobs/notify-client-auto.ts): 75, 72, 6, 20, 3, 55 — их здесь нет.
 *  · 16 «Новая скидка», 17 «Окончание действия скидки» (F-05-035/036) — нужен источник «скидку назначили/повысили» и срок
 *    сгорания из программы лояльности; в ТЗ открыт вопрос про «0 дней» (F-05-036);
 *  · 19 «У сотрудника заканчивается график» (F-05-048);
 *  · 85 «Ссылка на оплату», 65 «Оплата прошла» — онлайн-оплаты визита в платформе ещё нет.
 * Сделали отправку на сервере — уберите код отсюда.
 */
export const SERVER_SOON_TYPE_CODES: ReadonlySet<number> = new Set([16, 17, 19, 65, 85]);

export function isServerSoonType(code: number): boolean {
  return isApiMode() && SERVER_SOON_TYPE_CODES.has(code);
}
