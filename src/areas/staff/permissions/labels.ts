function hyLabel(ru: string): string | undefined {
  const pair = /^(Просматривать|Изменять) (.+)$/.exec(ru);
  if (pair && HY_CONCEPTS[pair[2]]) return `${pair[1] === 'Просматривать' ? 'Դիտել' : 'Խմբագրել'} ${HY_CONCEPTS[pair[2]]}`;
  const report = /^Отчёт (.+)$/.exec(ru);
  if (report && HY_REPORTS[report[1]]) return HY_REPORTS[report[1]];
  return HY_ROWS[ru];
}

/** Подпись права на языке кабинета; армянской нет — русская (как у словарей: нет ключа в hy — ru) */
export function permLabel(item: Pick<FinePermissionItem, 'label'>, locale: string): string {
  if (locale === 'en') return item.label.en;
  if (locale === 'hy') return hyLabel(item.label.ru) ?? item.label.ru;
  return item.label.ru;
}
